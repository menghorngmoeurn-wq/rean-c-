#include <iostream>
using namespace std;

int main(){

    int number = 10;

    cout <<"Before ++ : " << number << endl;
     
    number ++;
    
    cout<< "After ++ : "<< number << endl;

    cout << "====[--]====" << endl;

    cout<< "Before -- : " << number << endl;

    number --;

    cout << "After -- : " << number << endl;


    return 0;
}